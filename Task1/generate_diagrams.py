# Explicit sensitivity labels are independent of the risk/protection colours.
# These labels describe the stored data, not the implementation of access rules.
DATA_CLASSES = {
    "p1": {"D1": "Личные / медицинские"},
    "p2": {"D1": "Личные / медицинские"},
    "p3": {"D1": "Личные / медицинские"},
    "p4": {"D1": "Личные / медицинские"},
    "p5": {"D1": "Личные / финансовые", "D2": "Личные / финансовые"},
    "p6": {"D1": "Личные / медицинские / финансовые",
           "D2": "Личные / медицинские / финансовые"},
}
for name, data in all_diagrams:
    classes = DATA_CLASSES[name.split("-")[1]]
    for element in data["elements"]:
        if element["type"] == "store":
            element["badge"] = classes[element["id"]]
            if name == "dfd-p1-registration-to-be":
                element["badge"] = "Личные данные"
            if name == "dfd-p6-analytics-to-be" and element["id"] == "D2":
                element["badge"] = "Внутренние сводные данные"


def main():
    DIAGRAMS_DIR.mkdir(exist_ok=True)
    for name, data in all_diagrams:
        (DIAGRAMS_DIR / f"{name}.svg").write_text(render_svg(data), encoding="utf-8")
        print(f"Generated: {name}.svg")


if __name__ == "__main__":
    main()
