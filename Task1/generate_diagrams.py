def entity(identifier, title, subtitle=""):
    return dict(type="entity", id=identifier, title=title, subtitle=subtitle)


def process(identifier, title, subtitle, status):
    return dict(type="process", id=identifier, title=title,
                subtitle=subtitle, status=status)


def store(identifier, title, subtitle, status):
    return dict(type="store", id=identifier, title=title,
                subtitle=subtitle, status=status)


def diagram(title, subtitle, elements, flows, secure=False):
    return dict(title=title, subtitle=subtitle, elements=elements,
                flows=[dict(source=a, target=b, label=label,
                            style="secure" if secure else "vulnerable")
                       for a, b, label in flows])


